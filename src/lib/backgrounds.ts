export const DEFAULT_SHOWROOM_KEY = "showroom1.jpg";

export function isShowroomKey(key: string | null | undefined): key is string {
  if (!key) return false;
  return SHOWROOM_PRESETS.some((p) => p.key === key);
}

export function showroomPublicPath(key: string): string {
  return `/images/${key}`;
}

// Lightweight WebP thumbnail used only in the BackgroundPicker grid (the
// full-res /images/<key> file is still what composite.ts loads on apply).
// Generated by scripts/gen-thumbs.ts into /public/images/thumbs/.
export function showroomThumbPath(key: string): string {
  const base = key.replace(/\.[^.]+$/, "");
  return `/images/thumbs/${base}.webp`;
}

// Derives the R2 key of a custom background's thumbnail from its full-res key.
// Generated on apply in changeBackground(); the picker presigns this (with a
// fallback to the full key for backgrounds uploaded before thumbs existed).
export function customBgThumbKey(key: string): string {
  return `${key}.thumb.webp`;
}
